import re
import io
from typing import List, Dict, Tuple

import streamlit as st
from pypdf import PdfReader

st.set_page_config(page_title="AI Knowledge Assistant", page_icon="📚", layout="centered")
st.title("AI Knowledge Assistant")
st.caption("Ask a focused question about an uploaded PDF. Answers are based on retrieved text, with page references.")

def clean_text(s: str) -> str:
    return re.sub(r"\s+", " ", s or "").strip()

def tokens(s: str) -> List[str]:
    return [t.lower() for t in re.findall(r"[A-Za-z0-9][A-Za-z0-9'-]*", s)]

def make_chunks(pdf_bytes: bytes, chunk_words: int = 180, overlap: int = 35) -> List[Dict]:
    reader = PdfReader(io.BytesIO(pdf_bytes))
    chunks = []
    for page_no, page in enumerate(reader.pages, start=1):
        text = clean_text(page.extract_text() or "")
        words = text.split()
        if not words:
            continue
        step = max(1, chunk_words - overlap)
        for start in range(0, len(words), step):
            snippet = " ".join(words[start:start + chunk_words]).strip()
            if snippet:
                chunks.append({"page": page_no, "text": snippet})
    return chunks

def score(question: str, text: str) -> float:
    q = set(tokens(question))
    d = tokens(text)
    if not q or not d:
        return 0.0
    counts = {}
    for t in d:
        counts[t] = counts.get(t, 0) + 1
    # Simple term overlap with a small frequency bonus; no external service required.
    matched = sum(1 + min(counts.get(t, 0), 3) * 0.08 for t in q if t in counts)
    return matched / (len(q) ** 0.7)

def sentence_candidates(text: str) -> List[str]:
    parts = re.split(r"(?<=[.!?])\s+|(?<=:)\s+", text)
    return [p.strip(" •-\t") for p in parts if len(p.split()) >= 4]

def answer_question(question: str, chunks: List[Dict]) -> Tuple[str, List[Dict]]:
    ranked = sorted(
        [{"page": c["page"], "text": c["text"], "score": score(question, c["text"])} for c in chunks],
        key=lambda x: x["score"], reverse=True
    )
    best = [x for x in ranked if x["score"] > 0][:3]
    if not best or best[0]["score"] < 0.35:
        return "I couldn't find enough relevant information in this PDF to answer that question.", []
    q_terms = set(tokens(question))
    candidates = []
    for chunk in best:
        for sent in sentence_candidates(chunk["text"]):
            stoks = set(tokens(sent))
            overlap = len(q_terms & stoks) / max(1, len(q_terms))
            if overlap > 0:
                candidates.append((overlap, sent, chunk["page"]))
    candidates.sort(reverse=True, key=lambda x: x[0])
    chosen, seen = [], set()
    for _, sent, page in candidates:
        key = sent.lower()
        if key not in seen:
            chosen.append((sent, page))
            seen.add(key)
        if len(chosen) == 2:
            break
    if chosen:
        answer = " ".join(x[0] for x in chosen)
        pages = sorted(set(x[1] for x in chosen))
    else:
        answer = best[0]["text"]
        pages = [best[0]["page"]]
    words = answer.split()
    if len(words) > 65:
        answer = " ".join(words[:65]).rstrip(" ,;:") + "…"
    refs = [{"page": p} for p in pages]
    return answer, refs

uploaded = st.file_uploader("Upload an approved PDF knowledge source", type=["pdf"])
if uploaded:
    try:
        chunks = make_chunks(uploaded.getvalue())
        if not chunks:
            st.error("No selectable text was found. This may be a scanned PDF; OCR is not included in this prototype.")
        else:
            st.success(f"PDF ready: {len(chunks)} text passages indexed.")
            question = st.text_input("What would you like to know?", placeholder="Ask one specific question…")
            if st.button("Find answer", type="primary", disabled=not question.strip()):
                with st.spinner("Searching the document…"):
                    answer, refs = answer_question(question, chunks)
                st.subheader("Answer")
                st.write(answer)
                if refs:
                    st.caption("Source page(s): " + ", ".join(str(r["page"]) for r in refs))
                    with st.expander("Show supporting passages"):
                        for r in refs:
                            page_chunks = [c for c in chunks if c["page"] == r["page"]]
                            st.markdown(f"**Page {r['page']}**")
                            for c in page_chunks[:1]:
                                st.write(c["text"][:900] + ("…" if len(c["text"]) > 900 else ""))
    except Exception as e:
        st.error(f"Could not read this PDF: {e}")
else:
    st.info("Upload a text-based PDF to begin.")
st.caption("Prototype limitation: retrieval is keyword-based and answers are extracted from matching sentences, not generated by an LLM. Verify important answers against the cited page.")
